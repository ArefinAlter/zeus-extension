// Type generation shared by gen-types.mjs and check.mjs: json-schema-to-typescript (a
// development-only dependency) over the committed native-messaging schema. Cross-file $refs of the
// form https://zeus.invalid/schema/<name> are resolved from schema/ instead of the network.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { repoRoot } from './manifest.mjs';

const ID_PREFIX = 'https://zeus.invalid/schema/';

/** @param {string} file */
const readSchema = (file) => JSON.parse(readFileSync(join(repoRoot, 'schema', file), 'utf8'));

export const GENERATED_FILE = join(repoRoot, 'src', 'lib', 'protocol.generated.ts');

/** @returns {Promise<string>} the TypeScript source for the native-messaging protocol */
export async function generateTypes() {
  const nm = readSchema('native-messaging.v1.schema.json');
  // The schema file has only $defs, so give the compiler a root that references every message def.
  const root = {
    ...nm,
    title: 'NativeMessagingV1',
    type: 'object',
    properties: {
      extension_to_daemon: { $ref: '#/$defs/ExtensionToDaemonMessage' },
      daemon_to_extension: { $ref: '#/$defs/DaemonToExtensionMessage' },
      host_manifest_chrome: { $ref: '#/$defs/HostManifestChrome' },
      host_manifest_firefox: { $ref: '#/$defs/HostManifestFirefox' },
    },
  };
  const resolver = {
    order: 1,
    /** @param {{ url: string }} file */
    canRead: (file) => file.url.startsWith(ID_PREFIX),
    /** @param {{ url: string }} file */
    read: (file) => {
      const name = file.url.slice(ID_PREFIX.length).split('#')[0];
      return JSON.stringify(readSchema(`${name}.schema.json`));
    },
  };
  const generated = await compile(root, 'NativeMessagingV1', {
    bannerComment: [
      '/* eslint-disable */',
      '// GENERATED by scripts/gen-types.mjs from schema/*.json. Do not edit by hand.',
      '// Regenerate with: npm run gen:types',
    ].join('\n'),
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: false,
    cwd: join(repoRoot, 'schema'),
    $refOptions: { resolve: { zeus: resolver, http: false, file: false } },
  });
  // Schema descriptions can leave trailing spaces on empty generated documentation lines.
  return generated.replace(/[ \t]+$/gm, '');
}
